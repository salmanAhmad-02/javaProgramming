class Program1{
	public static void main(String[] args){
		System.out.println('a'+10);
		System.out.println('@');
		System.out.println('@'+10);
		System.out.println('@'-10);
		System.out.println('@'+'d');
		System.out.println(2+2);
		System.out.println('2'+2);
		System.out.println("2"+2);
		System.out.println('2'+'2');
		System.out.println('R'-'r');
		
	}
}
